/**
 * Client-Side Image to Base64 Converter Core Logic
 *
 * Requirements:
 * - 100% In-browser conversion using native FileReader API.
 * - Extracts and separates raw Base64 string vs complete RFC 2397 Data URL.
 * - Accurately computes dimensions, original binary size, and Base64 size.
 * - Computes and explains Base64 encoding overhead (~33% expansion).
 * - Enforces safe input size caps (15 MB) to prevent browser memory exhaustion.
 * - Zero local storage persistence, zero telemetry transmission of image payloads.
 */

import {
  validateImageMagicBytes,
  validateImageFileMetadata,
  formatFileBytes,
} from "./image-compressor.ts";

export const MAX_IMAGE_BASE64_FILE_SIZE_BYTES = 15 * 1024 * 1024; // 15 MB safeguard

export interface ImageBase64Result {
  rawBase64: string;
  dataUrl: string;
  mimeType: string;
  originalSizeBytes: number;
  base64Length: number;
  overheadBytes: number;
  overheadPercentage: number;
  width: number;
  height: number;
  filename: string;
}

/**
 * Calculates the exact byte expansion between original binary and Base64 string.
 */
export function calculateBase64Overhead(
  originalBytes: number,
  base64Length: number
): { overheadBytes: number; overheadPercentage: number } {
  if (originalBytes <= 0) {
    return { overheadBytes: 0, overheadPercentage: 0 };
  }
  const overheadBytes = Math.max(0, base64Length - originalBytes);
  const overheadPercentage = Number(
    ((overheadBytes / originalBytes) * 100).toFixed(1)
  );
  return { overheadBytes, overheadPercentage };
}

/**
 * Converts an image file to Base64 and returns structured metadata.
 */
export async function convertImageFileToBase64(
  file: File
): Promise<ImageBase64Result> {
  const metaValidation = validateImageFileMetadata(file);
  if (!metaValidation.valid) {
    throw new Error(metaValidation.error || "Invalid image file.");
  }

  if (file.size > MAX_IMAGE_BASE64_FILE_SIZE_BYTES) {
    throw new Error(
      `File size (${formatFileBytes(file.size)}) exceeds the ${MAX_IMAGE_BASE64_FILE_SIZE_BYTES / (1024 * 1024)} MB limit for browser Base64 string processing.`
    );
  }

  const arrayBuffer = await file.arrayBuffer();
  const magicValidation = validateImageMagicBytes(new Uint8Array(arrayBuffer));
  if (!magicValidation.valid) {
    throw new Error(magicValidation.error || "File signature validation failed.");
  }

  // Read as Data URL via FileReader
  const dataUrl = await new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      if (typeof reader.result === "string") {
        resolve(reader.result);
      } else {
        reject(new Error("FileReader failed to produce a valid string."));
      }
    };
    reader.onerror = () => reject(new Error("Failed to read image file."));
    reader.readAsDataURL(file);
  });

  // Extract raw Base64 by stripping data URI prefix
  const commaIndex = dataUrl.indexOf(",");
  if (commaIndex === -1) {
    throw new Error("Malformed data URL generated by browser.");
  }

  const rawBase64 = dataUrl.slice(commaIndex + 1);
  const mimeType = magicValidation.detectedMimeType || file.type || "image/png";

  // Read natural image dimensions
  const blobUrl = URL.createObjectURL(file);
  const img = new Image();
  let width = 0;
  let height = 0;

  try {
    await new Promise<void>((resolve, reject) => {
      img.onload = () => {
        width = img.naturalWidth;
        height = img.naturalHeight;
        resolve();
      };
      img.onerror = () => reject(new Error("Failed to decode image dimensions."));
      img.src = blobUrl;
    });
  } finally {
    URL.revokeObjectURL(blobUrl);
  }

  const { overheadBytes, overheadPercentage } = calculateBase64Overhead(
    file.size,
    rawBase64.length
  );

  return {
    rawBase64,
    dataUrl,
    mimeType,
    originalSizeBytes: file.size,
    base64Length: rawBase64.length,
    overheadBytes,
    overheadPercentage,
    width,
    height,
    filename: file.name,
  };
}
